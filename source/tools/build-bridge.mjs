// `npm run build:bridge`: bundles the Python bridge into dist/bridge.mjs, so
// Python can start it with plain `node` (no tsx, faster start-up).
import { build } from 'esbuild';

await build({
  entryPoints: ['src/ai/bridge.ts'],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node18',
  outfile: 'dist/bridge.mjs',
  banner: { js: '// Generated by tools/build-bridge.mjs. Do not edit.' },
});
console.log('dist/bridge.mjs written');
